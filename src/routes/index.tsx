import { useEffect, useState } from 'react'
import { createFileRoute } from '@tanstack/react-router'
import { toast } from 'sonner'

import { Analyzer, WINDOW_SIZES } from '@/components/ticklens/analyzer'
import { Scanner } from '@/components/ticklens/scanner'
import { SettingsDialog, useSettings } from '@/components/ticklens/settings'
import { useDerivConnection, useMarketScanner, useSyntheticMarkets, useTickFeed } from '@/hooks/use-deriv'
import type { ConnectionStatus } from '@/lib/deriv'
import { cn } from '@/lib/utils'

export const Route = createFileRoute('/')({
  component: Home,
})

const SCANNER_WINDOW = 500

function Home() {
  const { settings, save, ready } = useSettings()
  const [settingsOpen, setSettingsOpen] = useState(false)
  const [symbol, setSymbol] = useState('R_100')
  const [windowSize, setWindowSize] = useState(WINDOW_SIZES[3])
  const [barrier, setBarrier] = useState(4)
  const [running, setRunning] = useState(false)
  const [scanning, setScanning] = useState(false)

  // Two sockets: one for the focused analysis, one for the all-markets scan,
  // so the same symbol can be streamed by both without "AlreadySubscribed".
  const main = useDerivConnection(settings, ready)
  const scan = useDerivConnection(settings, ready && scanning)
  const markets = useSyntheticMarkets(main.client, main.status)
  const market = markets.find((m) => m.symbol === symbol) ?? markets[0]
  const feed = useTickFeed(main.client, main.status, market, windowSize, running)
  const entries = useMarketScanner(scan.client, scan.status, markets, SCANNER_WINDOW, scanning)

  const connectionError = main.error ?? scan.error
  useEffect(() => {
    if (!connectionError) return
    toast.error(connectionError.message, {
      id: connectionError.code,
      description: connectionError.code === 'InvalidAppID' ? 'Check the App ID in Connection settings.' : undefined,
      action: { label: 'Settings', onClick: () => setSettingsOpen(true) },
    })
  }, [connectionError])

  const analyze = (next: string) => {
    setSymbol(next)
    setRunning(true)
    document.getElementById('analyzer')?.scrollIntoView({ behavior: 'smooth', block: 'start' })
  }

  return (
    <div className="grid-bg min-h-screen">
      <header className="sticky top-0 z-30 border-b bg-background/80 backdrop-blur">
        <div className="mx-auto flex max-w-7xl items-center justify-between gap-4 px-4 py-3">
          <div className="flex items-center gap-3">
            <Logo />
            <div>
              <div className="font-display text-lg leading-none font-bold tracking-tight">TickLens</div>
              <div className="text-xs text-muted-foreground">Synthetic digit analyzer</div>
            </div>
          </div>
          <div className="flex items-center gap-2">
  <StatusPill status={main.status} />

  <button
    type="button"
    onClick={() => {
      window.location.href =
        'https://oauth.deriv.com/oauth2/authorize?app_id=34NM6oGFpDwmMKeg8t9fU'
    }}
    className="rounded-md bg-primary px-3 py-2 text-sm font-medium text-primary-foreground"
  >
    Connect to Deriv
  </button>

  <SettingsDialog
    settings={settings}
    onSave={save}
    open={settingsOpen}
    onOpenChange={setSettingsOpen}
  />
</div>
            
            
          
        </div>
      </header>

      <main className="mx-auto max-w-7xl space-y-10 px-4 py-8">
        <div className="max-w-3xl space-y-2">
          <h1 className="text-3xl font-bold tracking-tight md:text-4xl">
            Every tick, every digit, <span className="text-primary">in real time.</span>
          </h1>
          <p className="text-muted-foreground">
            Pick a Deriv synthetic market, press start, and TickLens reads its tick history and live tick stream to show
            last-digit probabilities, even/odd, over/under, rise/fallnd a prediction for the next digit.
          </p>
        </div>

        <div id="analyzer" className="scroll-mt-20">
          <Analyzer
            markets={markets}
            market={market}
            onMarketChange={setSymbol}
            windowSize={windowSize}
            onWindowSizeChange={setWindowSize}
            barrier={barrier}
            onBarrierChange={setBarrier}
            running={running}
            onToggle={() => setRunning((r) => !r)}
            connected={main.status === 'open'}
            feed={feed}
          />
        </div>

        <Scanner
          markets={markets}
          entries={entries}
          barrier={barrier}
          running={scanning}
          onToggle={() => setScanning((s) => !s)}
          onAnalyze={analyze}
          activeSymbol={running ? market?.symbol : undefined}
          windowSize={SCANNER_WINDOW}
        />
      </main>

      <footer className="border-t">
        <div className="mx-auto max-w-7xl px-4 py-6 text-xs leading-relaxed text-muted-foreground">
          Synthetic indices are generated by a certified random number generator. Percentages describe past ticks and
          predictions are statistical estimates, not guarantees — trade responsibly. Market data provided by the Deriv
          API.
        </div>
      </footer>
    </div>
  )
}

function StatusPill({ status }: { status: ConnectionStatus }) {
  const label = { idle: 'Offline', connecting: 'Connecting', open: 'Live', closed: 'Reconnecting' }[status]
  return (
    <span className="flex items-center gap-2 rounded-full border px-3 py-1 text-xs font-medium" aria-live="polite">
      <span className="relative flex size-2">
        {status === 'open' && <span className="absolute inline-flex size-full animate-ping rounded-full bg-up opacity-60" />}
        <span
          className={cn(
            'relative inline-flex size-2 rounded-full',
            status === 'open' ? 'bg-up' : status === 'idle' ? 'bg-muted-foreground' : 'bg-warn',
          )}
        />
      </span>
      {label}
    </span>
  )
}

function Logo() {
  return (
    <svg viewBox="0 0 32 32" className="size-9" aria-hidden>
      <rect width="32" height="32" rx="9" fill="var(--primary)" />
      <path
        d="M6 20 L11 14 L15 18 L20 9 L26 15"
        fill="none"
        stroke="var(--primary-foreground)"
        strokeWidth="2.6"
        strokeLinecap="round"
        strokeLinejoin="round"
      />
      <circle cx="26" cy="15" r="2.4" fill="var(--primary-foreground)" />
    </svg>
  )
}
